#!/usr/bin/env python3
"""Append the Korean catalog's Hangul glyphs to the cluster font atlases."""
import json
from pathlib import Path
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy import ndimage

ROOT = Path(__file__).resolve().parent.parent
SHARED = ROOT / 'cluster-shared'
LOCALE = ROOT / 'kit/runtime/locales/ko.json'
UP = 4
SPREAD = 8
BASE = 0.79


def glyph(font, ch, cell_w, cell_h):
    width, height = cell_w * UP, cell_h * UP
    image = Image.new('L', (width, height), 0)
    ImageDraw.Draw(image).text((width / 2, height * BASE), ch, font=font, fill=255, anchor='ms')
    inside = np.asarray(image) >= 128
    to_out = ndimage.distance_transform_edt(inside)
    to_in = ndimage.distance_transform_edt(~inside)
    signed = np.where(inside, to_out - 0.5, -(to_in - 0.5)) / UP
    signed = signed[UP // 2::UP, UP // 2::UP]
    return np.clip(np.round((0.5 + signed / (2 * SPREAD)) * 255), 0, 255).astype(np.uint8)


def main(font_file):
    source = (SHARED / 'font_baked.js').read_text()
    metadata = json.loads(source[source.index('=') + 1:].strip().rstrip(';'))
    catalog = json.loads(LOCALE.read_text())
    wanted = ''.join(sorted({ch for value in catalog.values() for ch in value if '\uac00' <= ch <= '\ud7a3'}))
    for family, meta in metadata.items():
        missing = ''.join(ch for ch in wanted if ch not in meta['chars'])
        if not missing:
            continue
        cell_w, cell_h, cols = meta['cellW'], meta['cellH'], meta['cols']
        old_rows = meta['rows']
        old = np.frombuffer((SHARED / ('font_' + family + '.wad')).read_bytes(), dtype=np.uint8).reshape(old_rows * cell_h, cols * cell_w)
        chars = meta['chars'] + missing
        rows = -(-len(chars) // cols)
        atlas = np.zeros((rows * cell_h, cols * cell_w), np.uint8)
        atlas[:old.shape[0], :old.shape[1]] = old
        font = ImageFont.truetype(font_file, int(round(cell_h * 0.92 * UP)), index=1)
        advances = []
        for offset, ch in enumerate(missing, start=len(meta['chars'])):
            y, x = (offset // cols) * cell_h, (offset % cols) * cell_w
            atlas[y:y + cell_h, x:x + cell_w] = glyph(font, ch, cell_w, cell_h)
            advances.append(round(font.getlength(ch) / (cell_h * UP), 4))
        (SHARED / ('font_' + family + '.wad')).write_bytes(atlas.tobytes())
        meta['chars'] = chars
        meta['rows'] = rows
        meta['adv'].extend(advances)
        if 'NotoSansCJK-KR' not in meta['font']:
            meta['font'] += ' + NotoSansCJK-KR'
        print(f'{family}: appended {len(missing)} Hangul glyphs, {atlas.shape[1]} x {atlas.shape[0]}')
    (SHARED / 'font_baked.js').write_text(
        "'use strict';\n/* Cluster fonts with Korean glyphs; generated by cluster-tools/bake_korean_font.py. */\n"
        'module.exports = ' + json.dumps(metadata, ensure_ascii=False) + ';\n'
    )


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit('usage: bake_korean_font.py /path/to/NotoSansCJK-Regular.ttc')
    main(sys.argv[1])
